// criar um menu de escolha, sendo 1- entrar, 2- cadastrar, 3- editar, 0- sair

var escolhaMenu= 3

switch (escolhaMenu) {
    case 1:
        console.log("entrar")
        break // parar

    case 2:
        console.log("cadastrar")
        break // parar

    case 3:
        console.log("editar")
        break // parar

    case 0:
        console.log("sair")
        break // parar

    default:
        console.log("digita direito aí")
        break // parar
}



